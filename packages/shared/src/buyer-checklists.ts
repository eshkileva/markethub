export function buyerChecklistForCategory(categorySlug: string | null | undefined): string[] {
  if (!categorySlug) return DEFAULT_CHECKLIST;
  return BUYER_CHECKLISTS[categorySlug] ?? DEFAULT_CHECKLIST;
}

export function buyerQuestionsForCategory(
  categorySlug: string | null | undefined,
  parentCategorySlug?: string | null,
): string[] {
  if (categorySlug && BUYER_SELLER_QUESTIONS[categorySlug]) {
    return BUYER_SELLER_QUESTIONS[categorySlug].slice(0, 5);
  }
  if (parentCategorySlug && PARENT_SELLER_QUESTIONS[parentCategorySlug]) {
    return PARENT_SELLER_QUESTIONS[parentCategorySlug].slice(0, 5);
  }
  return DEFAULT_BUYER_QUESTIONS;
}
